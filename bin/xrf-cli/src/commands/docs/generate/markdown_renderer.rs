use super::command_reference::{ArgumentReference, CommandReference, GroupReference};

pub const GENERATED_HEADER: &str = "<!-- This file is generated by `xrf-cli docs generate`. Do not edit manually. -->";

/// Name of the anchor wrapping a group page's command sections.
pub const COMMANDS_ANCHOR: &str = "commands";

/// Name of the anchor wrapping the index page's group table.
pub const GROUPS_ANCHOR: &str = "groups";

/// Renders extracted command references into Markdown pages.
pub struct ReferenceMarkdownRenderer;

impl ReferenceMarkdownRenderer {
  /// Renders the index and one page per command group as `(file name, content)` pairs.
  pub fn render_pages(groups: &[GroupReference]) -> Vec<(String, String)> {
    let mut pages: Vec<(String, String)> = vec![(String::from("README.md"), Self::render_index_page(groups))];

    for group in groups {
      pages.push((format!("{}.md", group.slug), Self::render_group_page(group)));
    }

    pages
  }

  fn render_index_page(groups: &[GroupReference]) -> String {
    let mut page: String = format!(
      "{GENERATED_HEADER}\n\n# XRF CLI command reference\n\n\
       Reference for `xrf-cli` subcommands, generated from the clap command definitions. \
       This directory is fully generated: rebuild it with `cargo make docs-cli` instead of editing pages.\n\n\
       <!-- ANCHOR: {GROUPS_ANCHOR} -->\n\n\
       | Group | Commands |\n| ----- | -------- |\n"
    );

    for group in groups {
      let slug: &str = group.slug;
      let commands: Vec<String> = group
        .commands
        .iter()
        .map(|command| format!("[`{} {}`]({slug}.md#{})", group.slug, command.name, command.name))
        .collect();

      page.push_str(&format!("| [{}]({slug}.md) | {} |\n", group.label, commands.join(", ")));
    }

    page.push_str(&format!("\n<!-- ANCHOR_END: {GROUPS_ANCHOR} -->\n"));

    page
  }

  fn render_group_page(group: &GroupReference) -> String {
    let mut page: String = format!(
      "{GENERATED_HEADER}\n\n# {} commands\n\n<!-- ANCHOR: {COMMANDS_ANCHOR} -->\n",
      group.label
    );

    for command in &group.commands {
      page.push_str(&Self::render_command_section(command));
    }

    page.push_str(&format!("\n<!-- ANCHOR_END: {COMMANDS_ANCHOR} -->\n"));

    page
  }

  fn render_command_section(command: &CommandReference) -> String {
    let mut section: String = format!(
      "\n## `{}`\n",
      command.usage.split_whitespace().take(3).collect::<Vec<_>>().join(" ")
    );

    if let Some(about) = &command.about {
      section.push_str(&format!("\n{about}\n"));
    }

    section.push_str(&format!("\n```txt\n{}\n```\n", command.usage));

    if !command.arguments.is_empty() {
      section
        .push_str("\n| Option | Required | Default | Description |\n| ------ | -------- | ------- | ----------- |\n");

      for argument in &command.arguments {
        section.push_str(&Self::render_argument_row(argument));
      }
    }

    section
  }

  fn render_argument_row(argument: &ArgumentReference) -> String {
    let mut description: String = argument.help.clone().unwrap_or_default();

    let has_extras: bool = !argument.possible_values.is_empty() || argument.value_delimiter.is_some();

    if has_extras && !description.is_empty() && !description.ends_with('.') {
      description.push('.');
    }

    if !argument.possible_values.is_empty() {
      let values: Vec<String> = argument
        .possible_values
        .iter()
        .map(|value| format!("`{value}`"))
        .collect();

      description.push_str(&format!(" Possible values: {}.", values.join(", ")));
    }

    if let Some(delimiter) = argument.value_delimiter {
      description.push_str(&format!(" Accepts multiple values separated by `{delimiter}`."));
    }

    format!(
      "| `{}` | {} | {} | {} |\n",
      Self::escape_cell(&argument.display),
      if argument.is_required { "yes" } else { "" },
      argument
        .default_value
        .as_ref()
        .map(|value| format!("`{value}`"))
        .unwrap_or_default(),
      Self::escape_prose_cell(description.trim())
    )
  }

  /// Escapes Markdown table-cell delimiters and line breaks.
  fn escape_cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
  }

  /// Escapes a cell of prose, where an angle bracket is text rather than markup.
  ///
  /// Help text names a value placeholder as `<name>`, and a Markdown renderer reads that as an HTML
  /// tag it never sees closed: mdBook warns, and the rest of the sentence disappears from the page.
  /// A cell rendered as code needs the opposite treatment, which is why this is not `escape_cell`.
  fn escape_prose_cell(text: &str) -> String {
    Self::escape_cell(text).replace('<', "&lt;").replace('>', "&gt;")
  }
}

#[cfg(test)]
mod tests {
  use super::super::command_reference::{ArgumentReference, CommandReference, GroupReference};
  use super::{COMMANDS_ANCHOR, GENERATED_HEADER, GROUPS_ANCHOR, ReferenceMarkdownRenderer};

  fn build_group() -> GroupReference {
    GroupReference {
      slug: "example",
      label: "Example",
      commands: vec![CommandReference {
        name: String::from("example-command"),
        about: Some(String::from("Example command")),
        usage: String::from("xrf-cli example example-command [OPTIONS] --path <path>"),
        arguments: vec![
          ArgumentReference {
            display: String::from("-p, --path <path>"),
            help: Some(String::from("Path to input")),
            is_required: true,
            default_value: None,
            possible_values: Vec::new(),
            value_delimiter: None,
          },
          ArgumentReference {
            display: String::from("-l, --language <language>"),
            help: Some(String::from("Target language")),
            is_required: false,
            default_value: Some(String::from("all")),
            possible_values: vec![String::from("all"), String::from("ukr")],
            value_delimiter: None,
          },
        ],
      }],
    }
  }

  #[test]
  fn renders_group_page() {
    let pages: Vec<(String, String)> = ReferenceMarkdownRenderer::render_pages(&[build_group()]);

    assert_eq!(pages.len(), 2);
    assert_eq!(pages[0].0, "README.md");
    assert_eq!(pages[1].0, "example.md");

    // The anchor wraps the command sections and nothing else, so a page including it gets the
    // reference without this page's own title or generated-file banner.
    assert_eq!(
      pages[1].1,
      format!(
        "{GENERATED_HEADER}\n\n\
         # Example commands\n\n\
         <!-- ANCHOR: {COMMANDS_ANCHOR} -->\n\n\
         ## `xrf-cli example example-command`\n\n\
         Example command\n\n\
         ```txt\nxrf-cli example example-command [OPTIONS] --path <path>\n```\n\n\
         | Option | Required | Default | Description |\n\
         | ------ | -------- | ------- | ----------- |\n\
         | `-p, --path <path>` | yes |  | Path to input |\n\
         | `-l, --language <language>` |  | `all` | Target language. Possible values: `all`, `ukr`. |\n\n\
         <!-- ANCHOR_END: {COMMANDS_ANCHOR} -->\n"
      )
    );
  }

  /// Help text names placeholders as `<value>`; a Markdown renderer would read that as an HTML tag
  /// and drop the rest of the sentence, which is how a generated page loses text nobody edited.
  #[test]
  fn escapes_angle_brackets_in_prose_cells() {
    let group: GroupReference = GroupReference {
      slug: "example",
      label: "Example",
      commands: vec![CommandReference {
        name: String::from("example-command"),
        about: None,
        usage: String::from("xrf-cli example example-command"),
        arguments: vec![ArgumentReference {
          display: String::from("-n, --name <name>"),
          help: Some(String::from("Written as <name>.db0 and <name>.db1")),
          is_required: false,
          default_value: None,
          possible_values: Vec::new(),
          value_delimiter: None,
        }],
      }],
    };

    let pages: Vec<(String, String)> = ReferenceMarkdownRenderer::render_pages(&[group]);

    // Escaped where it is prose, left alone where the cell is already a code span.
    assert!(pages[1].1.contains("Written as &lt;name&gt;.db0 and &lt;name&gt;.db1"));
    assert!(pages[1].1.contains("`-n, --name <name>`"));
  }

  #[test]
  fn renders_index_with_anchors() {
    let pages: Vec<(String, String)> = ReferenceMarkdownRenderer::render_pages(&[build_group()]);

    assert!(
      pages[0]
        .1
        .contains("| [Example](example.md) | [`example example-command`](example.md#example-command) |")
    );
    // The table is anchored too, so an overview page can carry it without listing commands itself.
    assert!(pages[0].1.contains(&format!("<!-- ANCHOR: {GROUPS_ANCHOR} -->")));
    assert!(pages[0].1.contains(&format!("<!-- ANCHOR_END: {GROUPS_ANCHOR} -->")));
  }
}
